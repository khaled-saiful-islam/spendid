const squash = (s: string) => s.toLowerCase().replace(/[^a-z0-9]/g, "");

/**
 * The known service a typed name refers to ("netflix", "Netflix Premium", "Spotify Family"),
 * so a subscription added by name or found in spending still gets its logo.
 */
export function brandForName(name: string): SubscriptionBrand | undefined {
	const typed = squash(name);
	if (typed.length < 2) return undefined;
	const exact = SUBSCRIPTION_BRANDS.find(
		(b) => squash(b.name) === typed || b.key === typed,
	);
	if (exact) return exact;
	// "Spotify Family", "Unifi home fibre": the longest service name it starts with wins.
	let best: { brand: SubscriptionBrand; length: number } | undefined;
	for (const b of SUBSCRIPTION_BRANDS) {
		if (b.icon !== undefined || b.key.length < 3) continue;
		for (const stem of [squash(b.name), b.key])
			if (typed.startsWith(stem) && stem.length > (best?.length ?? 0))
				best = { brand: b, length: stem.length };
	}
	return best?.brand;
}

export const brandOf = (
	key: string | null | undefined,
): SubscriptionBrand | undefined =>
	SUBSCRIPTION_BRANDS.find((b) => b.key === key);
