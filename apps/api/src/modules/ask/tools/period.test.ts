import { describe, expect, it } from "vitest";
import { periodRange } from "./period";

describe("periodRange", () => {
	it.each([
		["today", "2026-10-18", "2026-10-18", "2026-10-18"],
		["yesterday", "2026-03-01", "2026-02-28", "2026-02-28"],
		["yesterday", "2024-03-01", "2024-02-29", "2024-02-29"],
		["this_week", "2026-10-18", "2026-10-12", "2026-10-18"],
		["this_week", "2026-10-12", "2026-10-12", "2026-10-12"],
		["last_week", "2026-10-18", "2026-10-05", "2026-10-11"],
		["this_month", "2026-10-18", "2026-10-01", "2026-10-18"],
		["last_month", "2026-10-18", "2026-09-01", "2026-09-30"],
		["last_month", "2026-03-31", "2026-02-01", "2026-02-28"],
		["last_month", "2024-03-15", "2024-02-01", "2024-02-29"],
		["last_month", "2026-01-10", "2025-12-01", "2025-12-31"],
		["this_year", "2026-10-18", "2026-01-01", "2026-10-18"],
		["last_year", "2026-10-18", "2025-01-01", "2025-12-31"],
		["last_7_days", "2026-10-18", "2026-10-12", "2026-10-18"],
		["last_30_days", "2026-03-01", "2026-01-31", "2026-03-01"],
	] as const)("%s on %s is %s to %s", (period, today, from, to) => {
		expect(periodRange(period, today)).toEqual({ from, to });
	});
});
